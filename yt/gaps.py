"""Ball-gap report (CLAUDE.md 6.3): where and when the tracker loses the ball.

    python -m yt.gaps            # writes reports/gaps.md

Aggregate statistics only; nothing frame-level from the match data is written.
"""

from __future__ import annotations

import os
import warnings

import numpy as np

from .features import runs
from .load import FPS, PITCH, ROOT, load_match

REPORT = os.path.join(ROOT, "reports", "gaps.md")


def gap_table(ball_vis: np.ndarray, graded: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Start and end (exclusive) of each run of missing ball inside graded frames."""
    return runs(~ball_vis & graded)


def near_change(starts: np.ndarray, ends: np.ndarray, labels: np.ndarray, window: int
                ) -> np.ndarray:
    """True for gaps that start or end within `window` frames of a change between H and A
    (ignoring D and X frames in between)."""
    alive = np.flatnonzero(np.isin(labels, ["H", "A"]))
    seq = labels[alive]
    change = alive[1:][seq[1:] != seq[:-1]]  # first frame of each new possession team
    if change.size == 0:
        return np.zeros(len(starts), dtype=bool)
    out = np.zeros(len(starts), dtype=bool)
    for i, (a, b) in enumerate(zip(starts, ends)):
        for t in (a, b):
            j = np.searchsorted(change, t)
            for k in (j - 1, j):
                if 0 <= k < len(change) and abs(change[k] - t) <= window:
                    out[i] = True
    return out


def report(labels: np.ndarray | None = None, dead: np.ndarray | None = None) -> str:
    m = load_match()
    vis = ~np.isnan(m.ball_xy[:, 0])
    s, e = gap_table(vis, m.graded)
    ln = e - s
    miss = ln.sum()
    lines = ["# Ball-gap report", "",
             "Graded frames only ({} frames). Generated by `python -m yt.gaps`.".format(
                 int(m.graded.sum())), ""]
    lines += [
        "| statistic | value |", "|---|---|",
        "| ball visible on graded frames | {:.1%} |".format(vis[m.graded].mean()),
        "| gaps | {} |".format(len(ln)),
        "| median gap | {:.1f} s |".format(np.median(ln) / FPS),
        "| 90th percentile gap | {:.1f} s |".format(np.percentile(ln, 90) / FPS),
        "| longest gap | {:.1f} s |".format(ln.max() / FPS),
        "| missing frames in gaps over 10 frames | {:.1%} |".format(ln[ln > 10].sum() / miss),
        "| missing frames in gaps over 25 frames | {:.1%} |".format(ln[ln > 25].sum() / miss),
        "| missing frames in gaps over 10 s | {:.1%} |".format(ln[ln > 10 * FPS].sum() / miss),
    ]
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        p90 = np.nanpercentile(m.player_speed, 90, axis=1)
    lines += ["| median p90 player speed, ball visible | {:.2f} m/s |".format(
                  np.nanmedian(p90[m.graded & vis])),
              "| median p90 player speed, ball missing | {:.2f} m/s |".format(
                  np.nanmedian(p90[m.graded & ~vis]))]
    if dead is not None:
        live = m.graded & ~dead
        lines += ["| ball missing on frames we call live | {:.1%} |".format((~vis[live]).mean()),
                  "| ball missing on frames we call dead | {:.1%} |".format(
                      (~vis[m.graded & dead]).mean())]
    lines.append("")

    # where the ball was last seen before each gap
    L, W = PITCH
    last = np.array([m.ball_xy[a - 1] if a > 0 and vis[a - 1] else [np.nan, np.nan] for a in s])
    ok = ~np.isnan(last[:, 0])
    third = np.digitize(last[ok, 0], [L / 3, 2 * L / 3])
    lane = np.digitize(last[ok, 1], [W / 3, 2 * W / 3])
    lines += ["## Last seen position before a gap ({} gaps with a known position)".format(
        int(ok.sum())), "",
        "x is the pitch length in the tracking frame (not attack-relative); "
        "y lanes are the two touchline thirds and the centre.", "",
        "| x third \\ y lane | lane 1 | centre | lane 3 |", "|---|---|---|---|"]
    for t, name in enumerate(["x 0-35 m", "x 35-70 m", "x 70-105 m"]):
        row = [int(((third == t) & (lane == k)).sum()) for k in range(3)]
        lines.append("| {} | {} | {} | {} |".format(name, *row))
    lines.append("")

    if labels is not None:
        at_start = np.array([labels[a - 1] if a > 0 else "X" for a in s])
        lines += ["## Who had the ball when the gap started (our labels)", "",
                  "| label | gaps |", "|---|---|"]
        for lab in "HADX":
            lines.append("| {} | {} |".format(lab, int((at_start == lab).sum())))
        nc = near_change(s, e, labels, 2 * FPS)
        lines += ["", "Gaps that start or end within 2 s of a possession change (our labels): "
                  "**{} of {} ({:.0%})**.".format(int(nc.sum()), len(s), nc.mean()), ""]
    return "\n".join(lines) + "\n"


def main() -> None:
    import run_pipeline
    labels, info = run_pipeline.build()
    text = report(labels, info["dead"].dead)
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, "w") as fh:
        fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
